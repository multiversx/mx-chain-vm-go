package vmhooksgenerate

// WriteRustVMHooksLegacyTrait autogenerate data in the provided file
func WriteRustVMHooksSignatures(out *eiGenWriter, eiMetadata *EIMetadata) {
	autoGeneratedHeader(out)
	out.WriteString(`
use wasmparser::ValType;

use super::VmHookSignature;

#[rustfmt::skip]
pub const VM_HOOK_SIGNATURES: &[VmHookSignature] = &[
`)

	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(`    VmHookSignature::new("`)
		out.WriteString(lowerInitial(funcMetadata.Name))
		out.WriteString(`", &[`)
		for i, arg := range funcMetadata.Arguments {
			if i > 0 {
				out.WriteString(", ")
			}
			out.WriteString(rustWasmparserValType(arg.Type))
		}
		out.WriteString("], ")
		if funcMetadata.Result == nil {
			out.WriteString("None")
		} else {

			out.WriteString("Some(")
			out.WriteString(rustWasmparserValType(funcMetadata.Result.Type))
			out.WriteString(")")
		}
		out.WriteString("),\n")
	}

	out.WriteString(`];
`)

}
