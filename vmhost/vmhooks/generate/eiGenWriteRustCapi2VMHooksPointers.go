package vmhooksgenerate

import (
	"fmt"
)

// rustCapi2HookResultType renders the return type of a hook function pointer in the new C
// ABI. Every hook returns the same 16-byte struct regardless of its own result type: the
// value is widened to 64 bits and travels alongside the early-exit code, which is what gives
// a hook a way to report an early exit at all.
func rustCapi2HookResultType(_ *EIFunctionResult) string {
	return " -> vm_exec2_hook_result_t"
}

// WriteRustCapi2VMHooksPointers writes the Go-side function pointer table, as the new C API
// sees it.
func WriteRustCapi2VMHooksPointers(out *eiGenWriter, eiMetadata *EIMetadata) {
	autoGeneratedHeader(out)
	out.WriteString(`
use crate::capi_vm_hook_context::{vm_exec2_hook_context_t, vm_exec2_hook_result_t};

/// The Go VM's hook implementations, as a table of C function pointers.
///
/// Copied into Rust at executor creation; see CapiVMHookTable.
#[repr(C)]
#[derive(Clone)]
#[allow(non_camel_case_types)]
#[rustfmt::skip]
pub struct vm_exec2_vm_hook_c_func_pointers {`)

	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(fmt.Sprintf(
			"\n    pub %s: extern \"C\" fn%s",
			cgoFuncPointerFieldName(funcMetadata),
			writeRustFnDeclarationArguments(
				"ctx: *mut vm_exec2_hook_context_t",
				funcMetadata,
				rustCapiType,
				rustCapi2HookResultType,
			),
		))

		out.WriteString(",")
	}

	out.WriteString(`
}

impl std::fmt::Debug for vm_exec2_vm_hook_c_func_pointers {
    fn fmt(&self, f: &mut std::fmt::Formatter) -> std::fmt::Result {
        write!(f, "vm_exec2_vm_hook_c_func_pointers")
    }
}
`)
}
