package vmhooksgenerate

import (
	"fmt"
)

// WriteEIInterfaceLegacy writes the VM hooks interface as it was before the hooks learned to
// return errors.
//
// Flat, unlike VMHooks: the groups exist to keep that interface readable and nothing consumes
// them one by one, whereas this one has a single implementor and a single consumer.
func WriteEIInterfaceLegacy(out *eiGenWriter, eiMetadata *EIMetadata) {
	autoGeneratedGoHeader(out, "executor")
	out.WriteString(`
// VMHooksLegacy is the VM hooks interface in its pre-migration shape: every hook yields a
// plain value, and a hook that wants to stop execution has to arrange it as a side effect.
//
// It exists because an executor reached through a C API cannot do better. Its imported
// functions return a value and have nowhere to report that the hook wants execution to stop,
// so the exit has to be applied from inside the hook, before it returns. A backend that
// reports the outcome of a call properly lets the error travel back up instead, and consumes
// VMHooks directly.
//
// VMHooksLegacyAdapter is the bridge from VMHooks to here. Counterpart of the Rust
// VMHooksLegacy trait.
type VMHooksLegacy interface {
`)

	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(fmt.Sprintf("\t%s(", upperInitial(funcMetadata.Name)))
		for argIndex, arg := range funcMetadata.Arguments {
			if argIndex > 0 {
				out.WriteString(", ")
			}
			out.WriteString(fmt.Sprintf("%s %s", arg.Name, vmHooksType(arg.Type)))
		}
		out.WriteString(")")
		out.WriteString(goResultSignatureLegacy(funcMetadata, vmHooksType))
		out.WriteString("\n")
	}

	out.WriteString("}\n")
}
