package vmhooksgenerate

import (
	"fmt"
	"strings"
)

// WriteRustCapiOpcodeCost generates code for capi_opcode_cost.rs, under the given C type name.
//
// The name is a parameter because the legacy C API and the new one are now distinct surfaces
// that may end up in the same binary: the legacy types are `vm_legacy_*` so that nothing of
// theirs can collide with the shared `vm_exec_*` types the new crates publish, even though the
// layout is generated from this one opcode list either way.
func WriteRustCapiOpcodeCost(out *eiGenWriter, cTypeName string) {
	autoGeneratedHeader(out)
	out.WriteString("\nuse multiversx_chain_vm_executor::OpcodeCost;\n\n")
	out.WriteString("/// FFI-safe mirror of `OpcodeCost`.\n")
	out.WriteString("///\n")
	out.WriteString("/// This is a distinct type rather than a cast of `OpcodeCost` itself, so that\n")
	out.WriteString("/// the general-purpose struct is free to change shape without touching the C\n")
	out.WriteString("/// ABI, and vice versa.\n")
	out.WriteString("#[allow(non_camel_case_types)]\n")
	out.WriteString("#[repr(C)]\n")
	out.WriteString(fmt.Sprintf("pub struct %s {\n", cTypeName))

	costNames := LoadOpcodeNames().AllCostNames()

	for _, opcode := range costNames {
		out.WriteString(fmt.Sprintf("    pub opcode_%s: u32,\n", strings.ToLower(opcode)))
	}

	out.WriteString("}\n\n")
	out.WriteString(fmt.Sprintf("impl %s {\n", cTypeName))
	out.WriteString("    pub(crate) fn to_opcode_cost(&self) -> OpcodeCost {\n")
	out.WriteString("        OpcodeCost {\n")

	for _, opcode := range costNames {
		fieldName := strings.ToLower(opcode)
		out.WriteString(fmt.Sprintf("            opcode_%s: self.opcode_%s,\n", fieldName, fieldName))
	}

	out.WriteString("        }\n")
	out.WriteString("    }\n")
	out.WriteString("}\n")
}
