package vmhooksgenerate

import (
	"fmt"
)

// WriteRustVMHooksLegacyTrait autogenerate data in the provided file
func WriteRustVMHooksLegacyAdapter(out *eiGenWriter, eiMetadata *EIMetadata) {
	autoGeneratedHeader(out)
	out.WriteString(`
use std::{ffi::c_void, fmt};

use crate::{
    ExecutorRuntime, InstanceState, MemLength, MemPtr, VMHooks, VMHooksEarlyExit, VMHooksLegacy,
    with_vm_hooks_once,
};

/// Allow conversion from the new VMHooks to the old.
///
/// Will eventually be removed, once everything gets migrated.
///
/// The legacy import object wants a hooks *object*, built once and kept for the instance's
/// life, while a runtime lends hooks per call. This is the join: it holds the runtime and the
/// state of one instance, and on every hook call asks the runtime for hooks around that
/// state. So the execution a hook serves is resolved when the hook runs, exactly as on
/// Wasmer 6, and not captured when the instance was created.
///
/// The state is cloned per call because the legacy hooks are reached through a shared
/// reference. Backends make it a handle to the instance, so the clone is cheap.
pub struct VMHooksLegacyAdapter<R: ExecutorRuntime, S: InstanceState + Clone> {
    runtime: R,
    instance_state: S,
}

// VMHooksLegacy requires Debug. Implemented by hand rather than derived, so that neither the
// runtime nor the instance state has to be Debug just to be held here.
impl<R: ExecutorRuntime, S: InstanceState + Clone> fmt::Debug for VMHooksLegacyAdapter<R, S> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("VMHooksLegacyAdapter")
            .finish_non_exhaustive()
    }
}

impl<R: ExecutorRuntime, S: InstanceState + Clone> VMHooksLegacyAdapter<R, S> {
    pub fn new(runtime: R, instance_state: S) -> Self {
        VMHooksLegacyAdapter {
            runtime,
            instance_state,
        }
    }

    fn adapt_vm_hooks<F, T>(&self, f: F) -> T
    where
        T: Default,
        F: FnOnce(&mut dyn VMHooks) -> Result<T, VMHooksEarlyExit>,
    {
        let mut instance_state = self.instance_state.clone();

        let result = with_vm_hooks_once(
            |lend| self.runtime.with_vm_hooks(&mut instance_state, lend),
            f,
        );

        result.unwrap_or_else(|early_exit| {
            // A legacy hook returns a plain value and has nowhere to report an early exit,
            // so the instance has to be stopped and the exit stashed for the caller to pick
            // up once the call unwinds.
            instance_state
                .handle_early_exit_legacy(early_exit)
                .expect("could not record early exit");

            T::default()
        })
    }
}

#[rustfmt::skip]
impl<R: ExecutorRuntime, S: InstanceState + Clone> VMHooksLegacy for VMHooksLegacyAdapter<R, S> {
    fn set_vm_hooks_ptr(&mut self, _vm_hooks_ptr: *mut c_void) {
    }
`)

	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(fmt.Sprintf(
			"\n    fn %s%s {\n",
			snakeCase(funcMetadata.Name),
			writeRustFnDeclarationArguments(
				"&self",
				funcMetadata,
				rustVMHooksType,
				rustVMHooksLegacyReturnType,
			),
		))

		out.WriteString(fmt.Sprintf(
			"        self.adapt_vm_hooks(|inner| VMHooks::%s(inner",
			snakeCase(funcMetadata.Name),
		))
		for _, arg := range funcMetadata.Arguments {
			out.WriteString(", ")
			out.WriteString(snakeCase((arg.Name)))
		}
		out.WriteString("))\n")
		out.WriteString("    }\n")
	}

	out.WriteString("}\n")

}
