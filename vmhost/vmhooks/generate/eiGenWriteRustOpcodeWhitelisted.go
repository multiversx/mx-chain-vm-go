package vmhooksgenerate

import (
	"fmt"
)

// WriteOpcodeWhitelisted generates code for opcode_whitelisted.rs
func WriteOpcodeWhitelisted(out *eiGenWriter) {
	autoGeneratedHeader(out)
	allowUnwind := false
	allowedOpcodes := LoadOpcodeNames()

	out.WriteString(`
use wasmparser::Operator;

use super::OpcodeVersion;

pub fn is_opcode_whitelisted(op: &Operator, opcode_version: OpcodeVersion) -> bool {
    match opcode_version {
        OpcodeVersion::V1 => is_opcode_whitelisted_v1(op),
        OpcodeVersion::V2 => is_opcode_whitelisted_v2(op),
    }
}

fn is_opcode_whitelisted_v1(op: &Operator) -> bool {
    matches!(
        op,
`)

	for i, opcodeName := range allowedOpcodes.AllowedV1 {
		writeOperatorWhitelistMatchArm(out, allowUnwind, i, opcodeName)
	}

	out.WriteString(`    )
}

fn is_opcode_whitelisted_v2(op: &Operator) -> bool {
    matches!(
        op,
`)

	for i, opcodeName := range allowedOpcodes.AllowedV2 {
		writeOperatorWhitelistMatchArm(out, allowUnwind, i, opcodeName)
	}

	out.WriteString(`    )
}
`)

}

func writeOperatorWhitelistMatchArm(out *eiGenWriter, allowUnwind bool, i int, opcodeName string) {
	if !allowUnwind && opcodeName == "Unwind" {
		return
	}

	if i == 0 {
		out.WriteString(fmt.Sprintf("        Operator::%s { .. }\n", opcodeName))
		return
	}
	out.WriteString(fmt.Sprintf("            | Operator::%s { .. }\n", opcodeName))
}
