package vmhooksgenerate

import (
	"fmt"
)

// WriteVMHooksLegacyAdapter writes the adapter from VMHooks to VMHooksLegacy.
func WriteVMHooksLegacyAdapter(out *eiGenWriter, eiMetadata *EIMetadata) {
	autoGeneratedGoHeader(out, "executor")
	out.WriteString(`
// VMHooksLegacyAdapter presents error-returning VM hooks through the legacy, value-only
// signatures, applying the error as a side effect on the way out and returning the result
// the hook produced alongside it.
//
// Two things need it. A backend whose imported functions cannot carry an error, which is
// every backend reached through the old C API. And anything that simulates a contract -
// mock contracts, tests - because a contract never sees the error channel either: it is
// simply stopped.
//
// Counterpart of the Rust VMHooksLegacyAdapter, generated from the same metadata.
type VMHooksLegacyAdapter struct {
	vmHooks      VMHooks
	errorHandler VMHooksErrorHandler
}

// NewVMHooksLegacyAdapter wraps VM hooks so that they can be used through VMHooksLegacy.
//
// The error handler is a separate argument rather than being pulled off vmHooks, so that the
// two roles stay distinct; in practice one object plays both.
func NewVMHooksLegacyAdapter(vmHooks VMHooks, errorHandler VMHooksErrorHandler) *VMHooksLegacyAdapter {
	return &VMHooksLegacyAdapter{
		vmHooks:      vmHooks,
		errorHandler: errorHandler,
	}
}
`)

	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(fmt.Sprintf("\n// %s VM hook legacy adapter", upperInitial(funcMetadata.Name)))
		out.WriteString(fmt.Sprintf("\nfunc (adapter *VMHooksLegacyAdapter) %s(", upperInitial(funcMetadata.Name)))
		for argIndex, arg := range funcMetadata.Arguments {
			if argIndex > 0 {
				out.WriteString(", ")
			}
			out.WriteString(fmt.Sprintf("%s %s", arg.Name, vmHooksType(arg.Type)))
		}
		out.WriteString(")")
		out.WriteString(goResultSignatureLegacy(funcMetadata, vmHooksType))
		out.WriteString(" {")

		out.WriteString("\n\t")
		if funcMetadata.Result != nil {
			out.WriteString("result, err := ")
		} else {
			out.WriteString("err := ")
		}
		out.WriteString(fmt.Sprintf("adapter.vmHooks.%s(", upperInitial(funcMetadata.Name)))
		writeCommaSeparatedArgumentNames(out, funcMetadata.Arguments)
		out.WriteString(")")

		out.WriteString("\n\tif err != nil {")
		out.WriteString("\n\t\tadapter.errorHandler.HandleHookError(err)")
		out.WriteString("\n\t}")
		if funcMetadata.Result != nil {
			// The hook's own result, not the zero value. A failing hook returns a sentinel
			// (-1, 1, -2, ...) next to its error, the same value it returned back when it
			// applied the failure itself, and contracts branch on it. Zeroing here would
			// change what a contract reads. This is where Go departs from the Rust adapter,
			// whose hooks return a Result and so have no value to carry on the error path.
			out.WriteString("\n\treturn result")
		}

		out.WriteString("\n}\n")
	}
}
