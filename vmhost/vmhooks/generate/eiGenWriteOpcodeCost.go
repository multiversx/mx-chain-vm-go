package vmhooksgenerate

import "fmt"

// WriteBackendOpcodeCost writes the metered subset of the opcode costs, as the C-compatible
// struct one backend passes to its library. One copy per backend package, because the cgo
// type it is reinterpreted as is package-local.
func WriteBackendOpcodeCost(out *eiGenWriter, packageName string) {
	costNames := LoadOpcodeNames().AllCostNames()
	maxNameLength := maxCostNameLength(costNames)

	autoGeneratedHeader(out)

	out.WriteString(fmt.Sprintf(`
package %s

import "github.com/multiversx/mx-chain-vm-go/executor"

type OpcodeCost struct {`, packageName))

	for _, opcode := range costNames {
		out.WriteString("\n\t")
		out.WriteString(opcode)
		for i := len(opcode); i < maxNameLength; i++ {
			out.WriteString(" ")
		}
		out.WriteString(" uint32")
	}

	out.WriteString(`
}

// extractOpcodeCost narrows the VM's cost table to the opcodes this backend meters.
func extractOpcodeCost(wasmOps *executor.WASMOpcodeCost) *OpcodeCost {
	return &OpcodeCost{`)

	for _, opcode := range costNames {
		out.WriteString("\n\t\t")
		out.WriteString(opcode)
		out.WriteString(":")
		for i := len(opcode); i < maxNameLength; i++ {
			out.WriteString(" ")
		}
		out.WriteString(" wasmOps.")
		out.WriteString(opcode)
		out.WriteString(",")
		// out.WriteString(fmt.Sprintf("\t\t%s: wasmOps.%s,\n", opcode, opcode))
	}

	out.WriteString("\n\t}\n")
	out.WriteString("}\n")
}
