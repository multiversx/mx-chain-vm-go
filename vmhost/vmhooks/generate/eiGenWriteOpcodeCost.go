package vmhooksgenerate

// WriteExecutorOpcodeCost generates code for executor/opcodeCost.go
//
// One shared struct rather than one per backend. The opcodes it covers are a property of the
// gas schedule and of the metering middleware, not of the wasm runtime underneath, so every
// executor needs the same set in the same order. That is also why both C headers declare an
// identical vm_exec_opcode_cost_t: all three come from this one opcode list, which is what
// makes it sound for a backend to reinterpret the Go struct as its own C struct.
func WriteExecutorOpcodeCost(out *eiGenWriter) {
	costNames := LoadOpcodeNames().AllCostNames()
	maxNameLength := maxCostNameLength(costNames)

	autoGeneratedHeader(out)

	out.WriteString(`
package executor

// OpcodeCost is the gas cost of every opcode the executor meters.
//
// Distinct from WASMOpcodeCost, which carries the whole WASM opcode set as the gas schedule
// supplies it: this is the subset the metering middleware knows about, in the exact field
// order its FFI counterpart vm_exec_opcode_cost_t declares. Backends pass it across the
// boundary by reinterpreting one as the other, and each asserts that the two sizes agree.
type OpcodeCost struct {`)

	for _, opcode := range costNames {
		out.WriteString("\n\t")
		out.WriteString(opcode)
		for i := len(opcode); i < maxNameLength; i++ {
			out.WriteString(" ")
		}
		out.WriteString(" uint32")
	}

	out.WriteString(`
}

// ExtractOpcodeCost narrows the full WASM opcode cost set down to the opcodes the executor
// meters, in the field order the FFI expects.
func ExtractOpcodeCost(wasmOps *WASMOpcodeCost) *OpcodeCost {
	return &OpcodeCost{`)

	for _, opcode := range costNames {
		out.WriteString("\n\t\t")
		out.WriteString(opcode)
		out.WriteString(":")
		for i := len(opcode); i < maxNameLength; i++ {
			out.WriteString(" ")
		}
		out.WriteString(" wasmOps.")
		out.WriteString(opcode)
		out.WriteString(",")
	}

	out.WriteString("\n\t}\n")
	out.WriteString("}\n")
}
