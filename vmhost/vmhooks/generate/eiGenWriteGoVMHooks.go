package vmhooksgenerate

import (
	"fmt"
)

func eiGroupInterfaceName(group *EIGroup) string {
	return fmt.Sprintf("%sVMHooks", group.Name)
}

// writeEIInterfaceGroups writes the umbrella hooks interface and the per-group interfaces it
// is composed of.
//
// Shared by the two hook interfaces: they list the same hooks in the same groups and differ
// only in what their names are and in whether a hook reports an error.
func writeEIInterfaceGroups(
	out *eiGenWriter,
	eiMetadata *EIMetadata,
	interfaceName string,
	groupInterfaceName func(*EIGroup) string,
	resultSignature func(*EIFunction, func(EIType) string) string,
) {
	out.WriteString(fmt.Sprintf("type %s interface {", interfaceName))

	for _, group := range eiMetadata.Groups {
		out.WriteString(fmt.Sprintf("\n\t%s", groupInterfaceName(group)))
	}

	out.WriteString("\n}\n")

	for _, group := range eiMetadata.Groups {
		out.WriteString(fmt.Sprintf("\ntype %s interface {\n", groupInterfaceName(group)))

		for _, funcMetadata := range group.Functions {
			out.WriteString(fmt.Sprintf("\t%s(", upperInitial(funcMetadata.Name)))
			for argIndex, arg := range funcMetadata.Arguments {
				if argIndex > 0 {
					out.WriteString(", ")
				}
				out.WriteString(fmt.Sprintf("%s %s", arg.Name, vmHooksType(arg.Type)))
			}
			out.WriteString(")")
			out.WriteString(resultSignature(funcMetadata, vmHooksType))

			out.WriteString("\n")
		}

		out.WriteString("}\n")
	}
}

func WriteEIInterface(out *eiGenWriter, eiMetadata *EIMetadata) {
	autoGeneratedGoHeader(out, "executor")
	out.WriteString(`
// VMHooks contains all VM functions that can be called by the executor during SC execution.
`)
	writeEIInterfaceGroups(out, eiMetadata, "VMHooks", eiGroupInterfaceName, goResultSignature)
}

func externResult(functResult *EIFunctionResult) string {
	if functResult == nil {
		return "void"
	}
	return cgoType(functResult.Type)
}
