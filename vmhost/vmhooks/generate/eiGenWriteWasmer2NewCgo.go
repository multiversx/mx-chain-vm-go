package vmhooksgenerate

import (
	"fmt"
)

// The new C ABI's hook signature: a context pointer in, one 16-byte result struct out.
const (
	cgoNewContextType = "vm_exec_hook_context_t*"
	cgoNewResultType  = "vm_exec_hook_result_t"
)

type cgoNewWriter struct {
	goPackage  string
	cgoPrefix  string
	headerFile string
}

func (writer *cgoNewWriter) cgoFuncName(funcMetadata *EIFunction) string {
	return writer.cgoPrefix + lowerInitial(funcMetadata.Name)
}

// WriteWasmer2NewCgo writes the cgo shims for the new C API over Wasmer 2.2.
//
// Unlike the shims of the old C API, these return a result struct rather than a bare value,
// so a hook can report an early exit directly instead of signalling it out of band through a
// breakpoint global.
//
// The prefix is w2n_ rather than w2_, which the reference implementation uses, because in
// this repository the old C API's shims already hold w2_. A cgo //export name is a C symbol,
// and both packages are linked into the same binary, so the two sets must not collide.
func WriteWasmer2NewCgo(out *eiGenWriter, eiMetadata *EIMetadata) {
	writeCapiCgo(out, eiMetadata, &cgoNewWriter{
		goPackage:  "wasmer2new",
		cgoPrefix:  "w2n_",
		headerFile: "libvmexeccapi_w2.h",
	})
}

func writeCapiCgo(out *eiGenWriter, eiMetadata *EIMetadata, writer *cgoNewWriter) {
	writer.writeHeader(out, eiMetadata)
	writer.writeSignatureCheck(out, eiMetadata)
	writer.writePopulateFuncPointers(out, eiMetadata)
	writer.writeGoExports(out, eiMetadata)
}

func (writer *cgoNewWriter) writeHeader(out *eiGenWriter, eiMetadata *EIMetadata) {
	autoGeneratedGoHeader(out, writer.goPackage)

	// The header is included rather than the types re-declared, because the shims traffic in
	// two structs whose layout has to match the Rust side exactly.
	out.WriteString(fmt.Sprintf(`
// // Declare the function signatures (see [cgo](https://golang.org/cmd/cgo/)).
//
// #include <stdlib.h>
// #include "./%s"
//
`, writer.headerFile))

	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(fmt.Sprintf("// extern %s %s(%s ctx",
			cgoNewResultType,
			writer.cgoFuncName(funcMetadata),
			cgoNewContextType,
		))
		for _, arg := range funcMetadata.Arguments {
			out.WriteString(fmt.Sprintf(", %s %s", cgoType(arg.Type), arg.Name))
		}
		out.WriteString(");\n")
	}
}

// writeSignatureCheck emits a C initializer that assigns every exported shim to its field in
// the executor's hook table.
//
// It exists because nothing else checks that pairing. cgo types the table's fields as
// *[0]byte, so the Go assignment in populateCgoFunctionPointers accepts any function; and the
// extern declarations above are checked against the Go signatures, but not against the table.
// A C initializer is the one place both types are visible at once, so a shim whose arguments
// or result drifted from the field it is installed into fails the build here rather than
// corrupting the stack at the first call.
func (writer *cgoNewWriter) writeSignatureCheck(out *eiGenWriter, eiMetadata *EIMetadata) {
	out.WriteString(fmt.Sprintf(`//
// static const vm_exec_vm_hook_c_func_pointers %ssignature_check __attribute__((unused)) = {`,
		writer.cgoPrefix))

	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(fmt.Sprintf("\n//     .%s = %s,",
			cgoFuncPointerFieldName(funcMetadata),
			writer.cgoFuncName(funcMetadata),
		))
	}

	out.WriteString(`
// };
//
`)

	out.WriteString(`import "C"

import (
	"github.com/multiversx/mx-chain-vm-go/executor"
)

`)
}

func (writer *cgoNewWriter) writePopulateFuncPointers(out *eiGenWriter, eiMetadata *EIMetadata) {
	out.WriteString(`// populateCgoFunctionPointers builds the table of VM hook implementations handed to the
// executor at creation. The executor copies it, so the result does not need to outlive the
// call.
func populateCgoFunctionPointers() *C.vm_exec_vm_hook_c_func_pointers {
	return &C.vm_exec_vm_hook_c_func_pointers{`)

	maxNameLength := longestFuncNameLengthSnake(eiMetadata)
	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(fmt.Sprintf("\n\t\t%s:",
			cgoFuncPointerFieldName(funcMetadata),
		))

		numSpaces := maxNameLength - len(snakeCase(funcMetadata.Name)) + 1
		for i := 0; i < numSpaces; i++ {
			out.WriteString(" ")
		}

		out.WriteString(fmt.Sprintf("funcPointer(C.%s),",
			writer.cgoFuncName(funcMetadata),
		))
	}
	out.WriteString(`
	}
}
`)
}

func (writer *cgoNewWriter) writeGoExports(out *eiGenWriter, eiMetadata *EIMetadata) {
	for _, funcMetadata := range eiMetadata.AllFunctions {
		if !funcMetadata.ReturnsError {
			panic(fmt.Sprintf(
				"VM hook %s does not return an error; the new C API has no way to report one",
				funcMetadata.Name))
		}

		out.WriteString(fmt.Sprintf("\n//export %s\n",
			writer.cgoFuncName(funcMetadata),
		))
		out.WriteString(fmt.Sprintf("func %s(ctx *C.%s",
			writer.cgoFuncName(funcMetadata),
			"vm_exec_hook_context_t",
		))
		for _, arg := range funcMetadata.Arguments {
			out.WriteString(fmt.Sprintf(", %s %s", arg.Name, cgoExportType(arg.Type)))
		}
		out.WriteString(fmt.Sprintf(") C.%s {\n", cgoNewResultType))

		// Two results, where the reference implementation has one: there, VMHooks still
		// carried HandleHookError, and here the error handler is a separate interface.
		out.WriteString("\tvmHooks, errorHandler := getVMHooksFromHookContext(ctx)\n")
		out.WriteString("\t")
		if funcMetadata.Result != nil {
			out.WriteString("result, err := ")
		} else {
			out.WriteString("err := ")
		}

		out.WriteString(fmt.Sprintf("vmHooks.%s(",
			upperInitial(funcMetadata.Name),
		))
		for argIndex, arg := range funcMetadata.Arguments {
			if argIndex > 0 {
				out.WriteString(", ")
			}
			out.WriteString(cgoExportConversion(arg))
		}
		out.WriteString(")\n")

		out.WriteString("\tif err != nil {\n")
		out.WriteString("\t\treturn hookEarlyExit(errorHandler, err)\n")
		out.WriteString("\t}\n")

		if funcMetadata.Result != nil {
			out.WriteString("\treturn hookOk(int64(result))\n")
		} else {
			out.WriteString("\treturn hookOk(0)\n")
		}

		out.WriteString("}\n")
	}
}
