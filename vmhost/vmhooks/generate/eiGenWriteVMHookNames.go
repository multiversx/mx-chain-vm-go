package vmhooksgenerate

import (
	"fmt"
)

// WriteExecutorVMHookNames generates code for executor/vmHookNames.go
//
// One shared list rather than one per executor. These are the names of the VM hooks a contract
// may import, which is a property of the executor interface and of nothing below it: every
// backend offers the same set, because the same generator emits the same imports for all of
// them. Previously copied into wasmer2 and into the mock executor.
func WriteExecutorVMHookNames(out *eiGenWriter, eiMetadata *EIMetadata) {
	autoGeneratedGoHeader(out, "executor")
	out.WriteString(`
var empty struct{}

// VMHookNames is the set of low-level function names an executor provides to contracts.
var VMHookNames = map[string]struct{}{`)

	maxNameLength := longestFuncNameLengthCamel(eiMetadata)
	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(fmt.Sprintf("\n\t\"%s\":", lowerInitial(funcMetadata.Name)))
		numSpaces := maxNameLength - len(funcMetadata.Name) + 1
		for i := 0; i < numSpaces; i++ {
			out.WriteString(" ")
		}
		out.WriteString("empty,")
	}

	out.WriteString(`
}
`)
}
