package vmhooksgenerate

import (
	"fmt"
	"strings"
)

// rustCapiW6UnpackFn picks the helper that turns a hook result struct back into the
// `Result<_, VMHooksEarlyExit>` the VMHooks trait expects.
func rustCapiW6UnpackFn(result *EIFunctionResult) string {
	if result == nil {
		return "unpack_void"
	}
	switch result.Type {
	case EITypeInt32:
		return "unpack_i32"
	case EITypeInt64:
		return "unpack_i64"
	default:
		// MemPtr and MemLength are pointer-width on the Rust side, so they would need their
		// own narrowing. No hook returns one today; fail loudly rather than guess if one
		// ever does.
		panic(fmt.Sprintf("unsupported VM hook result type for the new C API: %v", result.Type))
	}
}

// WriteRustCapiW6VMHooks writes the implementation of the new VMHooks trait that dispatches
// to the Go side through the function pointer table.
func WriteRustCapiW6VMHooks(out *eiGenWriter, eiMetadata *EIMetadata) {
	autoGeneratedHeader(out)
	out.WriteString(`
use multiversx_chain_vm_executor::{MemLength, MemPtr, VMHooks, VMHooksEarlyExit};

use crate::capi_vm_hook_context::{vm_exec_w6_hook_context_t, vm_exec_w6_hook_result_t};
use crate::capi_vm_hook_pointers::vm_exec_w6_vm_hook_c_func_pointers;

/// Services one host call by dispatching each VM hook to the Go side.
///
/// Built on the stack for the duration of a single host call, around the hook context that
/// the Go side hands back to the state functions. It borrows the table rather than owning a
/// copy, because the executor already owns one for the lifetime of the instance.
pub struct CapiVMHooks<'a> {
    ctx: *mut vm_exec_w6_hook_context_t,
    func_pointers: &'a vm_exec_w6_vm_hook_c_func_pointers,
}

impl<'a> CapiVMHooks<'a> {
    pub fn new(
        ctx: *mut vm_exec_w6_hook_context_t,
        func_pointers: &'a vm_exec_w6_vm_hook_c_func_pointers,
    ) -> Self {
        CapiVMHooks { ctx, func_pointers }
    }

    fn convert_mem_ptr(&self, mem_ptr: MemPtr) -> i32 {
        mem_ptr as i32
    }

    fn convert_mem_length(&self, mem_length: MemLength) -> i32 {
        mem_length as i32
    }
}

impl std::fmt::Debug for CapiVMHooks<'_> {
    fn fmt(&self, f: &mut std::fmt::Formatter) -> std::fmt::Result {
        write!(f, "CapiVMHooks")
    }
}

/// An early-exit code travels back without its message.
///
/// The message stays on the Go side: the hook has already recorded it in the VM's own output
/// state before returning, and it could not cross anyway — cgo forbids returning an unpinned
/// Go pointer, and the messages are unbounded user text.
fn early_exit(code: u64) -> VMHooksEarlyExit {
    VMHooksEarlyExit::new(code)
}

fn unpack_void(result: vm_exec_w6_hook_result_t) -> Result<(), VMHooksEarlyExit> {
    match result.early_exit_code() {
        Some(code) => Err(early_exit(code)),
        None => Ok(()),
    }
}

fn unpack_i32(result: vm_exec_w6_hook_result_t) -> Result<i32, VMHooksEarlyExit> {
    match result.early_exit_code() {
        Some(code) => Err(early_exit(code)),
        None => Ok(result.value as i32),
    }
}

fn unpack_i64(result: vm_exec_w6_hook_result_t) -> Result<i64, VMHooksEarlyExit> {
    match result.early_exit_code() {
        Some(code) => Err(early_exit(code)),
        None => Ok(result.value),
    }
}

#[rustfmt::skip]
impl VMHooks for CapiVMHooks<'_> {
`)

	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(fmt.Sprintf(
			"    fn %s%s {\n",
			snakeCase(funcMetadata.Name),
			writeRustFnDeclarationArguments(
				"&mut self",
				funcMetadata,
				rustVMHooksType,
				rustVMHooksReturnType,
			),
		))

		out.WriteString(fmt.Sprintf(
			"        %s((self.func_pointers.%s)%s)\n",
			rustCapiW6UnpackFn(funcMetadata.Result),
			cgoFuncPointerFieldName(funcMetadata),
			writeRustCapiW6CallArguments(funcMetadata),
		))

		out.WriteString("    }\n")
	}

	out.WriteString(`}
`)
}

func writeRustCapiW6CallArguments(funcMetadata *EIFunction) string {
	var sb strings.Builder
	sb.WriteString("(self.ctx")
	for _, arg := range funcMetadata.Arguments {
		sb.WriteString(fmt.Sprintf(", %s", rustCapiConvertArg(arg)))
	}
	sb.WriteString(")")
	return sb.String()
}
